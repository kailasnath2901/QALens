import { NextRequest, NextResponse } from "next/server";
import { TestCase } from "@/types";

export async function POST(req: NextRequest) {
  try {
    const { projectCode, cases }: { projectCode: string; cases: TestCase[] } = await req.json();

    const qaseToken = process.env.QASE_API_TOKEN;

    if (!qaseToken) {
      return NextResponse.json({ success: false, error: "Qase API Token is not configured" }, { status: 400 });
    }

    if (!projectCode) {
      return NextResponse.json({ success: false, error: "Qase Project Code is required" }, { status: 400 });
    }

    const payload = {
      cases: cases.map(c => ({
        title: c.title,
        description: `Preconditions:\n${c.preconditions || 'None'}\n\nGenerated by QAlens AI (${c.provider})`,
        preconditions: c.preconditions || "",
        postconditions: "",
        severity: 3, // normal
        priority: 2, // medium
        status: 0, // actual
        steps: c.steps.map((stepText, idx) => ({
          position: idx + 1,
          action: stepText,
          expected_result: idx === c.steps.length - 1 ? c.expectedResult : ""
        }))
      }))
    };

    const response = await fetch(`https://api.qase.io/v1/case/${projectCode}/bulk`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "Token": qaseToken,
      },
      body: JSON.stringify(payload)
    });

    if (!response.ok) {
      const errorText = await response.text();
      return NextResponse.json({
        success: false,
        error: `Qase API error (${response.status}): ${errorText}`
      }, { status: response.status });
    }

    const data = await response.json();
    return NextResponse.json({ success: true, data });
  } catch (err: unknown) {
    const errorMessage = err instanceof Error ? err.message : "Failed to export test cases to Qase";
    return NextResponse.json({ success: false, error: errorMessage }, { status: 500 });
  }
}
