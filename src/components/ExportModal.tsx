"use client";

import React, { useState } from "react";
import { X, Download, Send, CheckCircle2, FileSpreadsheet, FileCode, FileText } from "lucide-react";
import { TestCase } from "@/types";

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  testCases: TestCase[];
  projectName: string;
}

export function ExportModal({ isOpen, onClose, testCases, projectName }: ExportModalProps) {
  const [qaseCode, setQaseCode] = useState("DEMO");
  const [exportingQase, setExportingQase] = useState(false);
  const [qaseStatus, setQaseStatus] = useState<string | null>(null);

  if (!isOpen) return null;

  const downloadCSV = () => {
    const headers = ["ID", "Title", "Category", "Preconditions", "Steps", "Expected Result", "Status", "Provider"];
    const rows = testCases.map(c => [
      c.id,
      `"${c.title.replace(/"/g, '""')}"`,
      c.category,
      `"${(c.preconditions || "").replace(/"/g, '""')}"`,
      `"${c.steps.join(" | ").replace(/"/g, '""')}"`,
      `"${c.expectedResult.replace(/"/g, '""')}"`,
      c.status,
      c.provider
    ]);

    const csvContent = "data:text/csv;charset=utf-8," + [headers.join(","), ...rows.map(r => r.join(","))].join("\n");
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement("a");
    link.setAttribute("href", encodedUri);
    link.setAttribute("download", `${projectName.toLowerCase().replace(/\s+/g, "_")}_testcases.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const downloadMarkdown = () => {
    let md = `# Test Suite: ${projectName}\n\n`;
    md += `*Generated by QAlens AI — Total Test Cases: ${testCases.length}*\n\n---\n\n`;

    testCases.forEach((c, idx) => {
      md += `### ${idx + 1}. ${c.title}\n`;
      md += `- **Category:** \`${c.category}\` | **Status:** \`${c.status}\` | **Provider:** \`${c.provider}\`\n`;
      if (c.preconditions) md += `- **Preconditions:** ${c.preconditions}\n`;
      md += `\n**Steps:**\n`;
      c.steps.forEach((s, sIdx) => {
        md += `${sIdx + 1}. ${s}\n`;
      });
      md += `\n**Expected Result:**\n> ${c.expectedResult}\n\n---\n\n`;
    });

    const blob = new Blob([md], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${projectName.toLowerCase().replace(/\s+/g, "_")}_test_cases.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const downloadJSON = () => {
    const jsonStr = JSON.stringify({ project: projectName, count: testCases.length, testCases }, null, 2);
    const blob = new Blob([jsonStr], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${projectName.toLowerCase().replace(/\s+/g, "_")}_testcases.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const syncToQase = async () => {
    if (!qaseCode.trim()) return;
    setExportingQase(true);
    setQaseStatus(null);
    try {
      const res = await fetch("/api/export/qase", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ projectCode: qaseCode, cases: testCases })
      });

      const data = await res.json();
      if (data.success) {
        setQaseStatus(`Successfully exported ${testCases.length} test cases to Qase project '${qaseCode.toUpperCase()}'!`);
      } else {
        setQaseStatus(`Export Failed: ${data.error}`);
      }
    } catch {
      setQaseStatus("Failed to communicate with Qase export endpoint");
    } finally {
      setExportingQase(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-md animate-fadeIn">
      <div className="w-full max-w-lg bg-gray-900 border border-gray-800 rounded-2xl p-6 shadow-2xl relative glow-indigo">
        <button
          onClick={onClose}
          className="absolute top-4 right-4 p-1 rounded-lg text-gray-400 hover:text-white hover:bg-gray-800"
        >
          <X className="w-5 h-5" />
        </button>

        <h2 className="text-lg font-bold text-white mb-1">
          Export Test Suite ({testCases.length} Cases)
        </h2>
        <p className="text-xs text-gray-400 mb-6">
          Download files or sync directly to external QA management tools
        </p>

        {/* File Export Options */}
        <div className="grid grid-cols-3 gap-3 mb-6">
          <button
            onClick={downloadCSV}
            className="flex flex-col items-center justify-center p-4 bg-gray-950 hover:bg-gray-850 border border-gray-800 hover:border-indigo-500 rounded-xl transition-all group"
          >
            <FileSpreadsheet className="w-6 h-6 text-emerald-400 mb-2 group-hover:scale-110 transition-transform" />
            <span className="text-xs font-semibold text-white">CSV</span>
            <span className="text-[10px] text-gray-500">Excel / Sheets</span>
          </button>

          <button
            onClick={downloadMarkdown}
            className="flex flex-col items-center justify-center p-4 bg-gray-950 hover:bg-gray-850 border border-gray-800 hover:border-indigo-500 rounded-xl transition-all group"
          >
            <FileText className="w-6 h-6 text-indigo-400 mb-2 group-hover:scale-110 transition-transform" />
            <span className="text-xs font-semibold text-white">Markdown</span>
            <span className="text-[10px] text-gray-500">Docs / GitHub</span>
          </button>

          <button
            onClick={downloadJSON}
            className="flex flex-col items-center justify-center p-4 bg-gray-950 hover:bg-gray-850 border border-gray-800 hover:border-indigo-500 rounded-xl transition-all group"
          >
            <FileCode className="w-6 h-6 text-cyan-400 mb-2 group-hover:scale-110 transition-transform" />
            <span className="text-xs font-semibold text-white">JSON</span>
            <span className="text-[10px] text-gray-500">Raw Data</span>
          </button>
        </div>

        {/* Integration Sync Section */}
        <div className="border-t border-gray-800 pt-5">
          <h3 className="text-xs font-semibold text-gray-300 uppercase tracking-wider mb-3">
            Push directly to Qase.io
          </h3>
          <div className="flex items-center gap-2 mb-3">
            <input
              type="text"
              value={qaseCode}
              onChange={(e) => setQaseCode(e.target.value.toUpperCase())}
              placeholder="Qase Project Code (e.g. DEMO)"
              className="flex-1 bg-gray-950 border border-gray-800 rounded-xl px-3 py-2 text-xs text-white uppercase placeholder-gray-600 focus:outline-none focus:border-indigo-500 font-mono"
            />
            <button
              onClick={syncToQase}
              disabled={exportingQase}
              className="px-4 py-2 bg-indigo-600 hover:bg-indigo-500 disabled:opacity-50 text-white rounded-xl text-xs font-semibold flex items-center gap-1.5 shadow-md transition-all"
            >
              <Send className="w-3.5 h-3.5" />
              <span>{exportingQase ? "Syncing..." : "Push Bulk"}</span>
            </button>
          </div>

          {qaseStatus && (
            <div className={`p-3 rounded-xl text-xs flex items-start gap-2 ${
              qaseStatus.includes("Successfully")
                ? "bg-emerald-950/40 border border-emerald-500/30 text-emerald-300"
                : "bg-red-950/40 border border-red-500/30 text-red-300"
            }`}>
              <CheckCircle2 className="w-4 h-4 flex-shrink-0 mt-0.5" />
              <span>{qaseStatus}</span>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
